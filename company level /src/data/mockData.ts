export const calculateStateCoverage = (terminalList: Terminal[]): StateCoverage[] => {
  const map: Record<string, { total: number; online: number; offline: number }> = {};
  terminalList.forEach(t => {
    if (!map[t.state]) {
      map[t.state] = { total: 0, online: 0, offline: 0 };
    }
    map[t.state].total++;
    if (t.connectivityStatus === 'ONLINE') {
      map[t.state].online++;
    } else {
      map[t.state].offline++;
    }
  });
  return Object.entries(map).map(([state, counts]) => ({
    state,
    total: counts.total,
    online: counts.online,
    offline: counts.offline,
  })).sort((a, b) => b.total - a.total);
};

